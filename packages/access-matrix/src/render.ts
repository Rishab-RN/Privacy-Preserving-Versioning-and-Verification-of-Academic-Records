import { decide, enumerateCases, resourcesFor } from './evaluate.js';
import { ACTIONS, ACTION_NAMES } from './model.js';
import type { Action, Principal, Via, World } from './model.js';
import { GRANTS } from './policy.js';

function duties(principal: Principal): string {
  const parts: string[] = [...principal.roles];
  for (const duty of principal.offeringDuties ?? []) parts.push(`${duty.duty} ${duty.offering}`);
  for (const duty of principal.departmentDuties ?? []) {
    parts.push(`${duty.duty} ${duty.department} ${duty.term}`);
  }
  for (const delegation of principal.delegations ?? []) {
    parts.push(
      `delegated ${delegation.tasks.join(', ')} for ${delegation.departments.join(', ')} ` +
        `until ${delegation.validUntil.slice(0, 10)}`,
    );
  }
  return parts.join('; ');
}

function via(grant: Via): string {
  switch (grant.kind) {
    case 'role':
      return `role ${grant.role}`;
    case 'offering':
    case 'department':
      return grant.stage ? `${grant.duty} (${grant.stage} only)` : grant.duty;
    case 'delegation':
      return `delegation ${grant.task}`;
  }
}

function grouped(entries: readonly (readonly [string, string])[]): string {
  if (entries.length === 0) return 'none';
  const byPrincipal = new Map<string, string[]>();
  for (const [principal, resource] of entries) {
    byPrincipal.set(principal, [...(byPrincipal.get(principal) ?? []), resource]);
  }
  return [...byPrincipal]
    .map(([principal, list]) => `${principal} → ${list.join(', ')}`)
    .join('; ');
}

function actionSection(world: World, action: Action): string[] {
  const principals = Object.keys(world.principals);
  const allowed: [string, string][] = [];
  const separated: [string, string][] = [];
  const outOfScope: [string, string][] = [];
  const forbidden: string[] = [];
  for (const principal of principals) {
    const outcomes = resourcesFor(world, action).map(
      (resource) => [resource, decide(world, principal, action, resource).outcome] as const,
    );
    for (const [resource, outcome] of outcomes) {
      if (outcome.status === 200) allowed.push([principal, resource]);
      else if (outcome.status === 404) outOfScope.push([principal, resource]);
      else if (outcome.code !== 'FORBIDDEN')
        separated.push([principal, `${resource} ${outcome.code}`]);
    }
    if (outcomes.every(([, outcome]) => outcome.code === 'FORBIDDEN')) forbidden.push(principal);
  }
  const spec = ACTIONS[action];
  if (spec.resource === 'public') {
    return [
      `### \`${action}\`: ${spec.summary}`,
      '',
      '- **Allowed:** everyone, including anonymous callers',
      '',
    ];
  }
  return [
    `### \`${action}\`: ${spec.summary}`,
    '',
    `- **Allowed:** ${grouped(allowed)}`,
    `- **Separation of duties (403):** ${grouped(separated)}`,
    `- **Outside scope (404):** ${grouped(outOfScope)}`,
    `- **No capability (403):** ${forbidden.length ? forbidden.join(', ') : 'none'}`,
    '- **No session (401):** anonymous callers',
    '',
  ];
}

/** Markdown view of the matrix for review. Regenerate it whenever policy or fixture changes. */
export function renderMatrix(world: World): string {
  const cases = enumerateCases(world);
  const count = (predicate: (status: number, code: string) => boolean) =>
    cases.filter(({ expected }) => predicate(expected.status, expected.code)).length;
  const separation = count((status, code) => status === 403 && code !== 'FORBIDDEN');

  const lines = [
    '# Pilot access matrix',
    '',
    '<!-- Generated by `npm run render --workspace @academic-records/access-matrix`. Do not edit by hand. -->',
    '',
    `Generated from \`src/policy.ts\` and the synthetic fixture in \`src/fixture.ts\` (${world.name}, evaluated at ${world.now}).`,
    'The evaluation order and status codes are described in the README. Grants based on `PROP` are',
    'prototype proposals awaiting RVCE confirmation.',
    '',
    `**${cases.length} cases:** ${count((s) => s === 200)} allowed, ${count((s) => s === 401)} unauthenticated, ` +
      `${count((s, c) => s === 403 && c === 'FORBIDDEN')} without capability, ${separation} separation-of-duties denials, ` +
      `${count((s) => s === 404)} outside scope.`,
    '',
    '## Personas',
    '',
    '| Key | Persona | Memberships, duties and delegations |',
    '| --- | --- | --- |',
    ...Object.entries(world.principals).map(
      ([key, principal]) => `| ${key} | ${principal.persona} | ${duties(principal)} |`,
    ),
    '',
    '## Outcomes by action',
    '',
    ...ACTION_NAMES.flatMap((action) => actionSection(world, action)),
    '## Grants',
    '',
    '| Action | Conferred by | Scope | Basis |',
    '| --- | --- | --- | --- |',
    ...GRANTS.map(
      (grant) =>
        `| \`${grant.action}\` | ${via(grant.via)} | ${grant.scope} | ${grant.basis.source}: ${grant.basis.locator} |`,
    ),
    '',
  ];
  return lines.join('\n');
}
